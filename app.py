"""Research demo: cross-dataset generalization of CNNs for pneumonia detection (chest X-ray).
Academic research prototype. NOT a diagnostic tool."""
from pathlib import Path

import streamlit as st
from PIL import Image

from cxr.engine import load_run
from cxr.gradcam import explain_image
from cxr.utils import get_device

ROOT = Path(__file__).parent
RES, SAMPLES = ROOT / "results", ROOT / "samples"

st.set_page_config(page_title="CXR Pneumonia - research demo", layout="wide")
st.title("Cross-dataset generalization for pneumonia detection (research prototype)")
st.warning("Academic research demo. Not clinically validated. Not for diagnosis or treatment decisions.")

runs = sorted(p.parent.name for p in RES.glob("*/best.pt"))


@st.cache_resource(show_spinner="Loading model...")
def get(run):
    return load_run(RES / run, get_device())


tab_demo, tab_res, tab_about = st.tabs(["Try a model", "Results", "About"])

with tab_demo:
    if not runs:
        st.info("No trained runs found in ./results.")
    else:
        default = runs.index("C_densenet121_imagenet_seed42") if "C_densenet121_imagenet_seed42" in runs else 0
        run = st.selectbox("Trained model (source dataset _ architecture _ normalization _ seed)", runs, index=default)
        samples = sorted(p.name for p in SAMPLES.glob("*.jpeg"))
        choice = st.selectbox("Image", ["Upload my own"] + samples)
        img, truth = None, None
        if choice == "Upload my own":
            up = st.file_uploader("Upload a chest X-ray (PNG/JPG)", type=["png", "jpg", "jpeg"])
            if up:
                img = Image.open(up)
        else:
            img = Image.open(SAMPLES / choice)
            truth = "Pneumonia" if choice.startswith("PNEUMONIA") else "Normal"
        if img is not None:
            model, cfg, thr = get(run)
            ov, rgb, probs = explain_image(model, cfg, img, get_device(), target=1)
            c1, c2 = st.columns(2)
            c1.image(rgb, caption="Input (as seen by model)")
            c2.image(ov, caption="Grad-CAM (pneumonia class)")
            st.metric("P(pneumonia)", f"{probs[1]:.3f}", help=f"Decision threshold from source validation: {thr:.3f}")
            st.write("Prediction at fixed threshold:", "**Pneumonia**" if probs[1] >= thr else "**Normal**")
            if truth:
                st.write("Dataset label of this sample:", f"**{truth}**")
            st.caption("Heatmaps are exploratory and do not prove the model uses clinically valid features.")

with tab_res:
    st.caption("Tables and figures generated by analyze.py / make_gradcam.py from the completed runs.")
    for md in sorted((RES / "tables").glob("*.md")):
        st.markdown(md.read_text())
    figs = sorted((RES / "figures").glob("*.png"))
    if figs:
        st.subheader("Figures")
        cols = st.columns(3)
        for i, f in enumerate(figs):
            cols[i % 3].image(str(f), caption=f.stem)
    gc = sorted((RES / "gradcam").glob("*.png"))
    if gc:
        st.subheader("Grad-CAM galleries (TP / TN / FP / FN)")
        pick = st.selectbox("Gallery", [g.stem for g in gc])
        st.image(str(RES / "gradcam" / f"{pick}.png"))

with tab_about:
    st.markdown(
        "Datasets: **A** = Chest X-Ray Images (Pneumonia, pediatric), **B** = NIH ChestX-ray14, **C** = CheXpert. "
        "Each model is trained on one source dataset and evaluated zero-shot on the others, with the decision threshold "
        "fixed from source validation data. Differences between datasets include patient population, equipment and "
        "labeling, so external drops (or gains) should be interpreted with those confounds in mind."
    )
